"""Shared configuration: loads the project's .env and resolves paths.

The .env file is searched for from the current directory upwards, so commands
must be run from the repository root (or any subdirectory).
Variables already set in the environment take precedence over .env.
"""
import os
from pathlib import Path

from dotenv import find_dotenv, load_dotenv

_ENV_FILE = find_dotenv(usecwd=True)
if _ENV_FILE:
    load_dotenv(_ENV_FILE, override=False)

PROJECT_ROOT = Path(_ENV_FILE).parent if _ENV_FILE else Path.cwd()


def env(name: str, default: str = "") -> str:
    return os.environ.get(name, default)


def env_int(name: str, default: int) -> int:
    return int(os.environ.get(name) or default)


def env_bool(name: str, default: bool = False) -> bool:
    v = os.environ.get(name)
    if v is None or not v.strip():
        return default
    return v.strip().lower() in ("1", "true", "yes", "on")


def env_path(name: str, default: str | Path) -> Path:
    """Path from the environment; relative paths are resolved against the project root."""
    p = Path(os.environ.get(name) or default).expanduser()
    return p if p.is_absolute() else PROJECT_ROOT / p


# Directory for state/cache generated by the tools (not tracked by git)
DATA_DIR = env_path("DATA_DIR", "data")
